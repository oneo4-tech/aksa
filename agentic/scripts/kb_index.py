"""Build .kb/index.md from the frontmatter of the Knowledge Base wiki pages.

Usage: uv run agentic/scripts/kb_index.py [--check]

Each page is wiki/<domain>/<topic>.md with frontmatter: summary (one line), tags
(a non-empty list), updated (a date), and optional sources (a list). The index
holds one line per page, grouped by domain, so agents can pick pages before
reading them. The page contract is in agentic/rules/knowledge.md.

Invalid pages are errors and the index is left untouched. --check validates
the pages and exits 1 if any is invalid or the index is out of date.
"""

import argparse
import datetime
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
KB = REPO_ROOT / ".kb"
MAX_CHARS = 6000  # about 1.5k tokens
NAME = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*")
FRONTMATTER = re.compile(r"---\n(.*?)\n---\n", re.DOTALL)
HEADER = [
    "# Knowledge index",
    "",
    "Generated by `uv run agentic/scripts/kb_index.py` in aksa; do not edit. One line per wiki page: link, summary, tags.",
]


def check_page(page: Path, kb: Path) -> tuple[dict, list[str]]:
    """The page's frontmatter and its problems; the frontmatter is usable only if there are none."""
    rel = page.relative_to(kb).as_posix()
    problems = []
    parts = page.relative_to(kb / "wiki").parts
    if len(parts) != 2 or not NAME.fullmatch(parts[0]) or not NAME.fullmatch(page.stem):
        problems.append(f"{rel}: must be wiki/<domain>/<topic>.md, lowercase hyphenated")
    text = page.read_text()
    if len(text) > MAX_CHARS:
        problems.append(f"{rel}: {len(text)} characters, over {MAX_CHARS}; split the page")
    match = FRONTMATTER.match(text)
    try:
        meta = yaml.safe_load(match.group(1)) if match else None
    except yaml.YAMLError as error:
        return {}, [*problems, f"{rel}: invalid frontmatter: {error}"]
    if not isinstance(meta, dict):
        return {}, [*problems, f"{rel}: missing frontmatter"]
    summary, tags = meta.get("summary"), meta.get("tags")
    if not isinstance(summary, str) or not summary.strip() or "\n" in summary.strip():
        problems.append(f"{rel}: summary must be one non-empty line")
    if not isinstance(tags, list) or not tags or not all(isinstance(t, str) and NAME.fullmatch(t) for t in tags):
        problems.append(f"{rel}: tags must be a non-empty list of lowercase hyphenated names")
    if not isinstance(meta.get("updated"), datetime.date):
        problems.append(f"{rel}: updated must be a date, YYYY-MM-DD")
    if not isinstance(meta.get("sources", []), list):
        problems.append(f"{rel}: sources must be a list")
    return meta, problems


def build_index(kb: Path) -> tuple[str, list[str]]:
    """The index text and the problems found in the wiki pages."""
    lines, problems, domain = list(HEADER), [], None
    for page in sorted((kb / "wiki").rglob("*.md")):
        meta, page_problems = check_page(page, kb)
        problems += page_problems
        if page_problems:
            continue
        if page.parent.name != domain:
            domain = page.parent.name
            lines += ["", f"## {domain}", ""]
        tags = " ".join(f"#{tag}" for tag in meta["tags"])
        lines.append(f"- [{page.stem}]({page.relative_to(kb).as_posix()}): {meta['summary'].strip()} {tags}")
    return "\n".join(lines) + "\n", problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate only, exit 1 if invalid or out of date")
    args = parser.parse_args()

    if not (KB / "wiki").is_dir():
        print(f"error: {KB / 'wiki'} not found; run agentic/scripts/link_external.py", file=sys.stderr)
        return 1
    text, problems = build_index(KB)
    for problem in problems:
        print(f"  error     {problem}")
    index = KB / "index.md"
    stale = not index.is_file() or index.read_text() != text
    if problems:
        print(f"\n{len(problems)} error(s); index.md left unchanged")
        return 1
    if args.check:
        print("  stale     index.md: run uv run agentic/scripts/kb_index.py" if stale else "  up to date")
        return 1 if stale else 0
    if stale:
        index.write_text(text)
        print("  update    index.md")
    else:
        print("  up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
